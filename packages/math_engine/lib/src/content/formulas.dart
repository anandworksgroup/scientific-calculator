/// Offline formula library content for the formula browser and the
/// "solve for any variable" calculator.
///
/// Pure data plus two tiny lookup helpers; no Flutter dependency.
library;

/// Subject area a [Formula] belongs to.
enum FormulaCategory {
  algebra,
  geometry,
  trigonometry,
  calculus,
  statistics,
  probability,
  physics,
  mechanics,
  electricity,
  magnetism,
  thermodynamics,
  optics,
  waves,
}

/// One symbol appearing in a formula.
class FormulaVariable {
  const FormulaVariable(this.id, this.latex, this.meaning, [this.unit = '']);

  /// Identifier used in [Formula.equation]; '' when the formula has no equation.
  final String id;

  /// How the symbol is written in the formula display (KaTeX).
  final String latex;

  /// Plain-language meaning, e.g. 'mass'.
  final String meaning;

  /// SI unit text, '' if dimensionless.
  final String unit;
}

/// A library formula.
class Formula {
  const Formula({
    required this.id,
    required this.name,
    required this.category,
    required this.latex,
    required this.description,
    this.variables = const [],
    this.related = const [],
    this.equation,
    this.keywords = const [],
  });

  /// Unique id, e.g. 'mechanics.kinetic_energy'.
  final String id;
  final String name;
  final FormulaCategory category;

  /// KaTeX-compatible display, one line.
  final String latex;

  /// Short original description (1–3 sentences).
  final String description;
  final List<FormulaVariable> variables;

  /// Ids of other formulas in [formulas].
  final List<String> related;

  /// Engine-syntax equation for the solver; null when not a single solvable equation.
  final String? equation;

  /// Extra search terms.
  final List<String> keywords;
}

typedef _V = FormulaVariable;
typedef _C = FormulaCategory;

/// Looks up a formula by its [Formula.id].
Formula? formulaById(String id) => _byId[id];

final Map<String, Formula> _byId = {for (final f in formulas) f.id: f};

/// Case-insensitive search over name, description, keywords and category name.
/// Results whose name matches come first.
List<Formula> searchFormulas(String query) {
  final q = query.trim().toLowerCase();
  if (q.isEmpty) return List.of(formulas);
  final terms = q.split(RegExp(r'\s+'));
  final nameHits = <Formula>[];
  final otherHits = <Formula>[];
  for (final f in formulas) {
    final name = f.name.toLowerCase();
    final hay = [name, f.description.toLowerCase(), f.category.name, ...f.keywords.map((k) => k.toLowerCase())].join(' ');
    if (!terms.every(hay.contains)) continue;
    if (terms.every(name.contains)) {
      nameHits.add(f);
    } else {
      otherHits.add(f);
    }
  }
  return [...nameHits, ...otherHits];
}

